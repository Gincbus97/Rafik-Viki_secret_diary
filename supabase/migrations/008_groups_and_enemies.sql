-- =============================================================================
-- Миграция #008 — Mob/Group как новый тип существа + поле enemies
-- Безопасна для повторного запуска.
-- =============================================================================

-- 1) Group/Mob — пятый kind. Подходит для безликой "толпы смертных",
--    которая взаимодействует с PC как целая сущность (банда, охотничий ковен,
--    толпа протестующих, отдел полиции, оперативная группа Inquisition и т.д.).
do $$ begin
  alter type creature_kind add value if not exists 'group';
exception when others then null; end $$;

-- 2) Поле "Враги" на персонаже — массив UUID других персонажей.
--    Доступно любому kind. Авто-отрисовывается на карте как Враг-связь.
alter table public.characters
  add column if not exists enemies jsonb not null default '[]'::jsonb;

-- 3) Готово.
